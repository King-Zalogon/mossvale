#!/usr/bin/env node
/* Generate docs/handoffs/INDEX.md from the per-task handoff files (#447).
   node scripts/handoffs-index.mjs write | check */
import {readdirSync, readFileSync, writeFileSync, existsSync} from 'node:fs';
import {join} from 'node:path';
import {fileURLToPath} from 'node:url';

const dir = fileURLToPath(new URL('../docs/handoffs/', import.meta.url));
const field = (text, name) => new RegExp(`^${name}:[ \\t]*(.+)$`, 'm').exec(text)?.[1].trim() ?? '';

export function renderIndex(files) {
  const rows = files.map(({name, text}) => {
    const title = /^#\s+(.+)$/m.exec(text)?.[1].trim() ?? name;
    return `| [${title.replaceAll('|', '/')}](${name}) | ${field(text, 'Issue')} | \`${field(text, 'Branch')}\` | ${field(text, 'Status')} | ${field(text, 'PR')} |`;
  });
  return [
    '# Handoff index',
    '',
    'Generated by `npm run handoffs:index` (part of `npm run regen`). Do not edit or merge by hand.',
    '',
    '| Task | Issue | Branch | Status | PR |',
    '| --- | --- | --- | --- | --- |',
    ...rows,
    '',
  ].join('\n');
}

export function readHandoffs() {
  return readdirSync(dir)
    .filter(name => name.endsWith('.md') && name !== 'README.md' && name !== 'INDEX.md')
    .sort()
    .map(name => ({name, text: readFileSync(join(dir, name), 'utf8')}));
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const expected = renderIndex(readHandoffs());
  const path = join(dir, 'INDEX.md');
  if (process.argv[2] === 'write') writeFileSync(path, expected);
  else if (process.argv[2] === 'check') {
    if (!existsSync(path) || readFileSync(path, 'utf8') !== expected) {
      console.error('docs/handoffs/INDEX.md is stale; run npm run regen');
      process.exit(1);
    }
  } else {
    console.error('usage: handoffs-index.mjs write|check');
    process.exit(2);
  }
}
